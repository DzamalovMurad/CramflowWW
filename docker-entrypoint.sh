#!/bin/sh
# Точка входа контейнера: чинит владельца тома и понижает привилегии.
#
# Railway монтирует Volume поверх каталога образа уже в рантайме, поэтому
# chown из Dockerfile до него не достаёт: том приходит с владельцем root,
# а процесс работает от flowix и не может писать — фото товаров из бота
# падали с «permission denied». Меняем владельца здесь, пока мы ещё root,
# и только потом отдаём управление приложению под непривилегированным
# пользователем: сам сервис root-правами не пользуется.
set -e

UPLOAD_DIR="${UPLOAD_DIR:-/app/uploads}"

if [ "$(id -u)" = "0" ]; then
	mkdir -p "$UPLOAD_DIR"
	# Том может быть большим: -R нужен только чтобы подобрать файлы,
	# записанные прежней версией от root. Ошибку не считаем фатальной —
	# при UPLOAD_STORE=db каталог вообще не используется.
	chown -R flowix:flowix "$UPLOAD_DIR" 2>/dev/null || true
	# Если su-exec почему-то не в образе, запускаем как есть: магазин, который
	# работает от root, лучше контейнера, который не стартует вовсе.
	if command -v su-exec >/dev/null 2>&1; then
		exec su-exec flowix "$@"
	fi
	echo "entrypoint: su-exec не найден — запуск без понижения привилегий" >&2
fi

exec "$@"
