def stems(comp):
    return sum(q for _, q in comp)

def pack_of(comp):
    n = stems(comp)
    for cap, price, label, row in PACK:
        if n <= cap:
            return price, label, row
    raise AssertionError

# ---------------------------------------------------------------- цены
def bump(c):
    """Цена, дающая маржу 55–60%, в формате «…90»."""
    newp = int((c / 0.425 - 90 + 99) // 100 * 100 + 90)
    while (newp - c) / newp < 0.55:
        newp += 100
    return newp

