-- Снятие колонки promo_codes.discount_percent, оставшейся вне миграций.
--
-- 0002 перенесла проценты в discount_type/discount_value и сняла старую
-- колонку. Позже на боевой базе её вернули руками — временной заплаткой
-- к AutoMigrate, когда код и схема разъехались. Заплатки больше нет,
-- код колонку не читает, но она осталась в схеме как второй, всегда
-- нулевой источник правды про размер скидки. Убираем: два поля про одни
-- и те же деньги рано или поздно разъезжаются.
--
-- Данных здесь нет: 0002 перенесла значения в discount_value до того, как
-- колонку вернули, и с тех пор в неё писался только DEFAULT 0.
-- IF EXISTS — на чистой базе колонки нет, и миграция просто ничего не делает.
ALTER TABLE promo_codes DROP COLUMN IF EXISTS discount_percent;
