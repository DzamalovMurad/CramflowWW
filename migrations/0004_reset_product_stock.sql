-- Возврат products.stock к исходному смыслу: NULL = учёт не ведётся.
--
-- 0001 объявила колонку nullable без DEFAULT: NULL — «не ограничиваем»,
-- число — реальный остаток, 0 — «закончилось». Позже на боевой базе
-- поработал AutoMigrate прежней версии кода, где поле было объявлено как
-- NOT NULL DEFAULT 0. Он навесил на колонку этот дефолт, и разница между
-- «учёт не ведём» и «ноль штук» исчезла: старые товары обнулились, новые
-- приходили из бота с нулём — вся витрина показывалась распроданной.
--
-- Снимаем ограничения и переводим нули обратно в NULL — тем же правилом,
-- что уже есть в 0001. Учёт остатков остаётся в коде: его включают из бота
-- (/edit → остаток), когда он действительно нужен.
ALTER TABLE products ALTER COLUMN stock DROP NOT NULL;
ALTER TABLE products ALTER COLUMN stock DROP DEFAULT;
UPDATE products SET stock = NULL WHERE stock = 0;
