// metroIndex — нормализованное имя → каноничное написание из MetroStations.
var metroIndex = func() map[string]string {
	m := make(map[string]string, len(MetroStations))
	for _, s := range MetroStations {
		m[normalizeStation(s)] = s
	}
	return m
}()

// normalizeStation убирает регистр, ё/е и разнобой в дефисах и пробелах:
// клиент может прислать «китай город» или «Тёплый  стан».
func normalizeStation(s string) string {
	s = strings.ToLower(strings.TrimSpace(s))
	s = strings.ReplaceAll(s, "ё", "е")
	s = strings.ReplaceAll(s, "-", " ")
	return strings.Join(strings.Fields(s), " ")
}

// NormalizeMetroStation возвращает каноничное название станции.
// Второе значение false, если такой станции в московском метро нет —
// в заказ попадают только названия из списка, а не произвольный текст.
func NormalizeMetroStation(s string) (string, bool) {
	name, ok := metroIndex[normalizeStation(s)]
	return name, ok
}
